#!/usr/bin/env python3
"""재채점 CSV → 논문용 표(Markdown, booktabs LaTeX), 원문 대조표, 국문 결과 문단, \\input 교체안.

숫자는 CSV 에서만 온다(수기 편집 금지). 표시 반올림은 이 스크립트에서만 한다(소수 첫째 자리).
    python scripts/export_det_sensitivity_table.py --run results/det_sensitivity_table/<run_id> [--config ...]
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
MODEL_LABEL = {"qwen25_coder_7b": "Qwen2.5-Coder-7B", "llama31_8b": "Llama-3.1-8B", "qwen25_coder_14b": "Qwen2.5-Coder-14B"}


def fmt(value: str | float, digits: int = 1, signed: bool = False) -> str:
    if value == "" or value is None:
        return "N/A"
    number = float(value)
    return f"{number:+.{digits}f}" if signed else f"{number:.{digits}f}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--config", default=str(REPO_ROOT / "configs/det_sensitivity_table.json"))
    args = ap.parse_args()
    run = Path(args.run)
    config = json.loads(Path(args.config).read_text(encoding="utf-8"))
    summary = list(csv.DictReader((run / "det_sensitivity_summary.csv").open(encoding="utf-8")))
    by_model = list(csv.DictReader((run / "det_sensitivity_by_model.csv").open(encoding="utf-8")))
    checks = json.loads((run / "checks.json").read_text(encoding="utf-8"))
    original = config["original_table_reference_only"]["rows"]
    cond_by_id = {c["id"]: c for c in config["conditions"]}

    # ---- original_vs_recomputed.csv
    ovr = []
    for row in summary:
        cid = row["condition_id"]; orig = original[cid]
        for col in ("dt", "gps", "diff"):
            key = {"dt": "dt_avg_pct", "gps": "gps_avg_pct", "diff": "diff_pp"}[col]
            rec = row[key]
            if rec == "":
                status = "N/A: 자료 부족(자기 모델용 GPS 최종 프롬프트 출력 없음)" if col != "dt" else "N/A"
                delta = ""
            else:
                delta = float(rec) - float(orig[col])
                status = "일치" if abs(delta) < 0.05 else ("반올림 차이" if abs(delta) < 0.1 else "실제 불일치")
            ovr.append({"condition_id": cid, "column": col, "original": orig[col], "recomputed_unrounded": rec,
                        "recomputed_rounded": fmt(rec), "delta_pp": delta, "status": status})
    with (run / "original_vs_recomputed.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(ovr[0].keys())); w.writeheader(); w.writerows(ovr)

    # ---- Markdown 표 (재계산)
    md = ["| 구분 | 민감도 조건 | DT (%) | GPS (%) | 차이 (%p) |", "|---|---|---:|---:|---:|"]
    for row in summary:
        label = row["row_label"] + ("" if row["gps_status"] == "computed" else "")
        md.append(f"| {row['group']} | {label} | {fmt(row['dt_avg_pct'])} | {fmt(row['gps_avg_pct'])} | {fmt(row['diff_pp'], signed=True)} |")
    md_table = "\n".join(md)
    # 진단 표(교차 적용 GPS 포함) — 논문 표가 아님
    md_diag = ["| 조건 | DT (%) | GPS* (%) | 차이* (%p) |", "|---|---:|---:|---:|"]
    for row in summary:
        md_diag.append(f"| {row['row_label']} | {fmt(row['dt_avg_pct'])} | {fmt(row['diagnostic_gps_avg_pct_incl_cross_applied'])} | {fmt(row['diagnostic_diff_pp_incl_cross_applied'], signed=True)} |")
    md_diag_table = "\n".join(md_diag)
    # 모델별 표
    md_model = ["| 조건 | 모델 | 방법 | 역할 | 통과/분모 | DETPass (%) | S_DET |", "|---|---|---|---|---:|---:|---:|"]
    for r in by_model:
        md_model.append(f"| {cond_by_id[r['condition_id']]['row_label']} | {MODEL_LABEL[r['model']]} | {r['method'].upper()} | {r['role']} | {r['passed']}/{r['denominator']} | {fmt(r['detpass_pct'], 2)} | {fmt(r['sdet'], 4)} |")

    # ---- LaTeX (booktabs, 위 τ 3행 / 아래 가중치 3행, 기준 행 강조)
    tex = ["% auto-generated by scripts/export_det_sensitivity_table.py — 수기 편집 금지",
           f"% run: {run.name}; 대상 모델 평균 = 세 모델 DETPass(각 280항목 micro)의 동일 가중 평균; 분모 280; 단일 run",
           "% GPS 열의 N/A: 7B·L8 의 자기 모델용 최종 프롬프트 출력이 없어 대상 모델 평균을 계산하지 않음",
           "\\begin{table}[t]", "\\centering",
           "\\caption{DET 가중치와 통과 임계값에 따른 민감도(대상 모델 평균 DETPass, \\%)}",
           "\\label{tab:det_sensitivity_target}",
           "\\begin{tabular}{llrrr}", "\\toprule",
           "구분 & 민감도 조건 & DT & GPS & 차이(\\%p) \\\\", "\\midrule"]
    groups = [c["group"] for c in config["conditions"]]
    for i, row in enumerate(summary):
        if i > 0 and row["group"] != summary[i - 1]["group"]:
            tex.append("\\midrule")
        cells = [row["group"] if (i == 0 or row["group"] != summary[i - 1]["group"]) else "", row["row_label"],
                 fmt(row["dt_avg_pct"]), fmt(row["gps_avg_pct"]), fmt(row["diff_pp"], signed=True)]
        line = " & ".join(cells) + " \\\\"
        if cond_by_id[row["condition_id"]].get("is_reference"):
            line = " & ".join([cells[0], f"\\textbf{{{cells[1]}}}"] + [f"\\textbf{{{c}}}" for c in cells[2:]]) + " \\\\"
        tex.append(line)
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (run / "tab_det_sensitivity.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")

    # ---- 국문 결과 문단 (숫자 자동 삽입)
    s = {row["condition_id"]: row for row in summary}
    dt85, dt90, dt95 = (fmt(s[c]["dt_avg_pct"]) for c in ("base_t085", "base_t090", "base_t095"))
    dtu, dte, dts = (fmt(s[c]["dt_avg_pct"]) for c in ("uniform_t090", "execution_t090", "structure_t090"))
    gps_avail = all(s[c]["gps_status"] == "computed" for c in s)
    p1 = ("식~(\\ref{eq:det_item_score})의 가중치와 식~(\\ref{eq:det_item_pass})의 통과 임계값이 비교 결과에 주는 영향을 확인하기 "
          "위해, 자연어 명령·서비스 문맥·기준 코드와 모델별 최종 프롬프트·생성 출력을 고정한 채 DET 내부 가중치 또는 통과 임계값만 "
          "바꾸어 재채점하였다. 재채점은 저장된 출력에서 여덟 비교값을 다시 추출해 가중합을 계산하며, LLM 추론·출력 수정·프롬프트 재선택·GA 재탐색을 하지 않는다.")
    p2 = (f"기준 가중치에서 임계값을 0.85, 0.90, 0.95 로 바꾸면 DirectTransfer 의 대상 모델 평균 DETPass 는 각각 {dt85}\\%, {dt90}\\%, {dt95}\\% 였다. "
          + ("" if gps_avail else "GPS-PromptOps 의 대상 모델 평균은 세 모델 중 한 모델(Qwen2.5-Coder-14B)의 모델별 최종 프롬프트 출력만 확보되어 계산하지 않았다(작업용 표 상태). "))
    p3 = (f"임계값 0.90 에서 가중치를 균등, 실행 의미 중심, 전체 구조 중심 배분(표~\\ref{{tab:det_weight_settings}})으로 바꾸면 DirectTransfer 는 각각 {dtu}\\%, {dte}\\%, {dts}\\% 로, "
          f"기준 배분({dt90}\\%) 대비 변화는 임계값 변화보다 작았다.")
    p4 = ("검토한 여섯 조건에서 GPS-PromptOps 의 우위 여부는 세 모델 모두의 모델별 최종 프롬프트 출력이 확보된 뒤에 판정한다. "
          "GA 를 다시 실행하지 않았으므로 이 표는 탐색 경로와 최종 선택의 안정성을 검증하지 않는다.")
    paragraphs = "\n\n".join([p1, p2, p3, p4])

    parse_note = f"파싱 실패(e=0, v=0) {checks['parse_failures']}행, 저장 성분과 재계산 성분 불일치 {checks['stored_component_mismatches']}행, 단조성 {'성립' if checks['monotonicity_ok'] else '위반'}, S_DET ≥ τ·DETPass {'성립' if checks['sdet_inequality_ok'] else '위반'}."
    results_md = f"""# DET 민감도 재채점 결과 — {run.name}

## 1. 재계산한 여섯 행(대상 모델 평균 DETPass, %) — 논문 표 형식

{md_table}

GPS 열의 N/A: Qwen2.5-Coder-7B 와 Llama-3.1-8B 는 자기 모델을 대상으로 탐색한 최종 프롬프트의 280행 출력이 없다.
14B 의 GPS 값은 아래 모델별 표에 있다. 이 표는 **작업용 표 상태**이며 완성된 논문 표가 아니다.

## 2. 진단(별도 분석): 14B 용 GPS 프롬프트를 7B·L8 에 교차 적용한 출력을 GPS 로 넣은 평균

{md_diag_table}

\\* 논문의 GPS-PromptOps 정의(모델별 탐색 프롬프트)와 다르므로 논문 표에 넣지 않는다.

## 3. 모델별 통과수·분모·DETPass·S_DET (단일 run, seed 0, repeat 0)

{chr(10).join(md_model)}

정합성: {parse_note}

## 4. 기존 표와의 대조

{chr(10).join(['| 조건 | 열 | 원문 | 재계산 | 차이(%p) | 상태 |', '|---|---|---:|---:|---:|---|'] + [f"| {r['condition_id']} | {r['column']} | {r['original']} | {r['recomputed_rounded']} | {fmt(r['delta_pp'], signed=True) if r['delta_pp'] != '' else ''} | {r['status']} |" for r in ovr])}

## 5. 논문용 국문 결과 문단(초안; 수치는 CSV 자동 삽입)

{paragraphs}
"""
    (run / "det_sensitivity_results.md").write_text(results_md, encoding="utf-8")
    replacement = f"""% paper_sensitivity_replacement.tex — 원고의 민감도 표 자리에 \\input 하는 교체안 (원본 논문 파일은 수정하지 않음)
% 상태: 작업용 표(GPS 열 N/A). 세 모델의 모델별 최종 프롬프트 출력이 확보되면 재실행 후 문단을 갱신한다.
\\input{{{run.as_posix()}/tab_det_sensitivity.tex}}

{paragraphs}
"""
    (run / "paper_sensitivity_replacement.tex").write_text(replacement, encoding="utf-8")
    print(md_table); print(); print(md_diag_table); print(); print(parse_note)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
